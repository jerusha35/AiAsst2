-- 1. DROP EXISTING OBJECTS (IN REVERSE DEPENDENCY ORDER)
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE TRANSACTIONS CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE WALLETS CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE USERS CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP SEQUENCE SEQ_USERS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP SEQUENCE SEQ_WALLETS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP SEQUENCE SEQ_TRANSACTIONS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- 2. CREATE SEQUENCES FOR AUTO-INCREMENTING PRIMARY KEYS
CREATE SEQUENCE SEQ_USERS
    START WITH 1001
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE SEQUENCE SEQ_WALLETS
    START WITH 5001
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE SEQUENCE SEQ_TRANSACTIONS
    START WITH 100001
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

-- 3. CREATE USERS TABLE
CREATE TABLE USERS (
    USER_ID         NUMBER,
    FULL_NAME       VARCHAR2(100) NOT NULL,
    EMAIL           VARCHAR2(150) NOT NULL,
    PHONE           VARCHAR2(15),
    PASSWORD_HASH   VARCHAR2(255) NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    STATUS          VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USERS_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE', 'SUSPENDED'))
);

-- Trigger for auto-populating USER_ID if not explicitly provided
CREATE OR REPLACE TRIGGER TRG_USERS_BI
BEFORE INSERT ON USERS
FOR EACH ROW
BEGIN
    IF :NEW.USER_ID IS NULL THEN
        SELECT SEQ_USERS.NEXTVAL INTO :NEW.USER_ID FROM DUAL;
    END IF;
END;
/

-- 4. CREATE WALLETS TABLE
CREATE TABLE WALLETS (
    WALLET_ID       NUMBER,
    USER_ID         NUMBER NOT NULL,
    BALANCE         NUMBER(12,2) DEFAULT 0.00 NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    STATUS          VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT PK_WALLETS PRIMARY KEY (WALLET_ID),
    CONSTRAINT UQ_WALLETS_USER UNIQUE (USER_ID),
    CONSTRAINT FK_WALLETS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT CK_WALLETS_BALANCE CHECK (BALANCE >= 0),
    CONSTRAINT CK_WALLETS_STATUS CHECK (STATUS IN ('ACTIVE', 'FROZEN', 'CLOSED'))
);

-- Trigger for auto-populating WALLET_ID if not explicitly provided
CREATE OR REPLACE TRIGGER TRG_WALLETS_BI
BEFORE INSERT ON WALLETS
FOR EACH ROW
BEGIN
    IF :NEW.WALLET_ID IS NULL THEN
        SELECT SEQ_WALLETS.NEXTVAL INTO :NEW.WALLET_ID FROM DUAL;
    END IF;
END;
/

-- 5. CREATE TRANSACTIONS TABLE
CREATE TABLE TRANSACTIONS (
    TRANSACTION_ID      NUMBER,
    TRANSACTION_REF     VARCHAR2(40) NOT NULL,
    SENDER_WALLET_ID    NUMBER NULL,
    RECEIVER_WALLET_ID  NUMBER NULL,
    TRANSACTION_TYPE    VARCHAR2(30) NOT NULL,
    AMOUNT              NUMBER(12,2) NOT NULL,
    DESCRIPTION         VARCHAR2(255),
    TRANSACTION_STATUS  VARCHAR2(20) DEFAULT 'SUCCESS' NOT NULL,
    CREATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_TRANSACTIONS PRIMARY KEY (TRANSACTION_ID),
    CONSTRAINT UQ_TXN_REF UNIQUE (TRANSACTION_REF),
    CONSTRAINT FK_TXN_SENDER FOREIGN KEY (SENDER_WALLET_ID) REFERENCES WALLETS(WALLET_ID),
    CONSTRAINT FK_TXN_RECEIVER FOREIGN KEY (RECEIVER_WALLET_ID) REFERENCES WALLETS(WALLET_ID),
    CONSTRAINT CK_TXN_AMOUNT CHECK (AMOUNT > 0),
    CONSTRAINT CK_TXN_TYPE CHECK (TRANSACTION_TYPE IN ('TOPUP', 'TRANSFER_SENT', 'TRANSFER_RECEIVED')),
    CONSTRAINT CK_TXN_STATUS CHECK (TRANSACTION_STATUS IN ('SUCCESS', 'FAILED', 'PENDING'))
);

-- Trigger for auto-populating TRANSACTION_ID if not explicitly provided
CREATE OR REPLACE TRIGGER TRG_TRANSACTIONS_BI
BEFORE INSERT ON TRANSACTIONS
FOR EACH ROW
BEGIN
    IF :NEW.TRANSACTION_ID IS NULL THEN
        SELECT SEQ_TRANSACTIONS.NEXTVAL INTO :NEW.TRANSACTION_ID FROM DUAL;
    END IF;
END;
/

-- 6. INDEXES FOR PERFORMANCE OPTIMIZATION
CREATE INDEX IDX_WALLETS_USER_ID ON WALLETS(USER_ID);
CREATE INDEX IDX_TXN_SENDER ON TRANSACTIONS(SENDER_WALLET_ID);
CREATE INDEX IDX_TXN_RECEIVER ON TRANSACTIONS(RECEIVER_WALLET_ID);
CREATE INDEX IDX_TXN_CREATED_AT ON TRANSACTIONS(CREATED_AT DESC);
CREATE INDEX IDX_TXN_REF ON TRANSACTIONS(TRANSACTION_REF);

-- 7. VERIFICATION QUERY (Optional check)
SELECT table_name FROM user_tables WHERE table_name IN ('USERS', 'WALLETS', 'TRANSACTIONS');

